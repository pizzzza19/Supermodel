#!/usr/bin/env python3
"""Regenerate the embedded native Metal shaders using the Vulkan SPIR-V inputs.

Requires SPIRV-Cross on PATH (or --spirv-cross PATH). Normal builds use the
checked-in headers and do not need Python, SPIRV-Cross, or a Vulkan runtime.
"""
import argparse
from pathlib import Path
import re
import struct
import subprocess
import tempfile


def generate(compiler, root):
    output = root / "Src/Graphics/Metal3D/Shaders"
    output.mkdir(parents=True, exist_ok=True)
    for name, stage in (("real3d", "vert"), ("real3d", "frag"),
                        ("fog", "vert"), ("fog", "frag"),
                        ("composite", "vert"), ("composite", "frag")):
        source = root / f"Src/Graphics/Vulkan3D/Shaders/{name}_{stage}.spv.h"
        array = source.read_text().split("{", 1)[1].split("}", 1)[0]
        words = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", array)]
        entry = f"{name}_{stage}"
        with tempfile.TemporaryDirectory() as temp:
            spirv = Path(temp) / "shader.spv"
            spirv.write_bytes(struct.pack(f"<{len(words)}I", *words))
            command = [compiler, str(spirv), "--msl", "--msl-version", "20100",
                       "--rename-entry-point", "main", entry, stage]
            # Vulkan's clip-space Y points down; Metal's points up. Keep the
            # Vulkan projection and tile UV conventions by flipping at the end.
            if stage == "vert":
                command.append("--flip-vert-y")
            metal = subprocess.check_output(command, text=True)
        # Bind native resources explicitly, independent of SPIRV-Cross's
        # automatic assignment. Vertex attributes use buffer 8 in Metal3D.mm.
        bindings = {"pc": 0, "ubo": 1, "materials": 2}
        for resource, index in bindings.items():
            metal = re.sub(r"(\b" + resource + r"\s*\[\[buffer\()\d+(\)\]\])",
                           lambda m: m[1] + str(index) + m[2], metal)
        # Arrays start at texture 0; the composite sampler starts at sampler 0.
        metal = re.sub(r"(\buPages\s*\[\[texture\()\d+(\)\]\])", r"\g<1>0\2", metal)
        metal = re.sub(r"(\buLayers\s*\[\[texture\()\d+(\)\]\])", r"\g<1>0\2", metal)
        header = ('// Generated by Scripts/Generate_MetalShaders.py. Do not edit.\n'
                  '// Derived from Supermodel-VK shaders, GPL-3.0-or-later.\n'
                  f'static const char {entry}_msl[] = R"METAL(\n{metal})METAL";\n')
        (output / f"{entry}.msl.h").write_text(header, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spirv-cross", default="spirv-cross")
    args = parser.parse_args()
    generate(args.spirv_cross, Path(__file__).resolve().parent.parent)
